import fs from 'fs';

async function generateSimpleBasicEnemy() {
  try {
    console.log('🚀 Loading BasicEnemy(7).json project...');

    // Cargar el proyecto JSON
    const projectData = JSON.parse(fs.readFileSync('./Examples/BasicEnemy(7).json', 'utf8'));
    console.log('✅ Project loaded:', projectData.assets ? `${projectData.assets.length} assets` : 'no assets found');

    // Analizar los assets
    let codeAssets = [];
    let tileAssets = [];
    let spriteAssets = [];

    for (const asset of projectData.assets || []) {
      if (asset.type === 'code') {
        codeAssets.push(asset);
      } else if (asset.type === 'tile') {
        tileAssets.push(asset);
      } else if (asset.type === 'sprite') {
        spriteAssets.push(asset);
      }
    }

    console.log(`📊 Found: ${codeAssets.length} code files, ${tileAssets.length} tiles, ${spriteAssets.length} sprites`);

    // Generar un archivo ASM básico unificado
    let unifiedASM = `; ==================================================================
; BASICENEMY - UNIFIED FILE
; File: unitedFiles.asm
; Description: All-in-one file combining all modular files
; Generated by Mideas MSX Modular Generator
; ==================================================================

; ==================================================================
; MSX CARTRIDGE ROM HEADER
; File: header.asm
; Description: Standard MSX cartridge initialization
; ==================================================================

    ORG #4000           ; MSX cartridge start address

; ==================================================================
; CARTRIDGE HEADER
; ==================================================================
    DB "AB"             ; MSX cartridge signature
    DW INIT_ROM         ; Initialization address
    DW 0                ; Statement handler (not used)
    DW 0                ; Device handler (not used)
    DW 0                ; Text handler (not used)
    DW 0                ; Reserved
    DW 0                ; Reserved
    DW 0                ; Reserved

; ==================================================================
; ROM INITIALIZATION ENTRY POINT
; ==================================================================
INIT_ROM:
    ; Disable interrupts during initialization
    DI

    ; Initialize stack for cartridge
    LD SP, #F380

    ; Initialize VDP for Screen 2 using BIOS
    LD A, 2
    CALL CHGMOD         ; Set Screen 2 mode (BIOS handles everything)

    ; Clear screen
    CALL CLS

    ; Enable interrupts
    EI

    ; Jump to main program
    JP MAIN_PROGRAM

`;

    // Agregar el código de los assets
    for (const codeAsset of codeAssets) {
      unifiedASM += `
; ==================================================================
; ${codeAsset.name.toUpperCase()}
; ==================================================================

${codeAsset.data}
`;
    }

    // Agregar sección principal básica
    unifiedASM += `
; ==================================================================
; MAIN PROGRAM
; ==================================================================
MAIN_PROGRAM:
    ; Program main loop
MAIN_LOOP:
    ; Wait for VBlank
    CALL WRTVRM

    ; Continue main loop
    JP MAIN_LOOP

; ==================================================================
; BIOS FUNCTIONS
; ==================================================================
CHGMOD: EQU #005F      ; Change screen mode
CLS:    EQU #00C3      ; Clear screen
WRTVRM: EQU #004D      ; Write to VRAM

    END
`;

    // Guardar el archivo
    const outputPath = './server/temp/basicenemy_generated.asm';
    fs.writeFileSync(outputPath, unifiedASM);
    console.log(`💾 Generated ASM file saved as: ${outputPath}`);
    console.log(`📏 File size: ${unifiedASM.length} bytes`);

  } catch (error) {
    console.error('❌ Generation failed:', error.message);
    console.error('Stack:', error.stack);
  }
}

generateSimpleBasicEnemy();