init_rom:
    di
    im 1
    ld sp, #F380
    call map_page2_to_cart_primary
    call init_konami8k_linear_banks

    ld a, #C9
    ld (HKEY), a
    xor a
    ld (CLIKSW), a

    call DISSCR
    ld a, 4
    call CHGMOD
    ld bc, #0007
    call WRTVDP
    ld bc, #0602
    call WRTVDP
    ld bc, #FF03
    call WRTVDP
    ld bc, #0304
    call WRTVDP
    ld bc, #000A
    call WRTVDP

    call load_screen4_palette
    ld a, 0
    ld (msx2_current_screen_index), a
    call init_msx2_effect_buffers
    call load_SNAKE_SUPERVISOR_ARENA_screen4

    call init_msx2_snake_char

    call init_msx2_snake_music
    call ENASCR
    ei

    ; MSX2 minimal GameFlow: Start/Text(background)/Transition(cls)/End.
    ld a, 0
    ld (msx2_current_screen_index), a
    call load_SNAKE_SUPERVISOR_ARENA_screen4
    call init_msx2_snake_char
    jp .main_loop

.main_loop:


    call update_msx2_snake_char

    call update_msx2_snake_music
    call wait_frame_busy
    jr .main_loop

wait_frame_busy:
    ; Simple ROM backend delay. Avoid HALT here so C-BIOS/OpenMSX smoke tests
    ; keep advancing even when no VBlank hook is installed by the minimal backend.
    ld bc, #0400
.wait_loop:
    dec bc
    ld a, b
    or c
    jp nz, .wait_loop
    ret

map_page2_to_cart_primary:
    ; Keep #8000-#BFFF on the same slot as the cart page at #4000,
    ; including expanded-slot cartridges.
    call RSLREG
    rrca
    rrca
    call get_cart_slot_value
    ld h, #80
    jp ENASLT

get_cart_slot_value:
    and #03
    ld c, a
    ld b, 0
    ld hl, #FCC1
    add hl, bc
    ld a, (hl)
    and #80
    jr z, .slot_ready
    or c
    ld c, a
    inc hl
    inc hl
    inc hl
    inc hl
    ld a, (hl)
    and #0C
.slot_ready:
    or c
    ret

init_konami8k_linear_banks:
    ; Harmless on simple 32K ROMs; required when the same image is forced
    ; as Konami 8K so #6000/#8000/#A000 expose linear banks 1/2/3.
    ld a, 1
    ld (#6000), a
    ld a, 2
    ld (#8000), a
    ld a, 3
    ld (#A000), a
    ret

wait_key:
    call CHGET
    ret

clear_screen4_names:
    xor a
    ld hl, SCREEN4_NAME_VRAM
    ld bc, SCREEN4_NAME_SIZE
    call FILVRM
    ret

clear_screen4_name_cell_16:
    ; HL=top-left SCREEN 4 name-table cell for a 16x16 block. Clobbers AF/BC/HL.
    xor a
    call WRTVRM
    inc hl
    xor a
    call WRTVRM
    ld bc, 31
    add hl, bc
    xor a
    call WRTVRM
    inc hl
    xor a
    call WRTVRM
    ret

psg_write_direct:
    ; Input: A=PSG register, E=value. Clobbers AF.
    out (#A0), a
    ld a, e
    out (#A1), a
    ret

init_msx2_snake_music:
    ; Minimal PSG loop for the SCREEN 4 Snake slice. Clobbers AF/BC/DE/HL.
    xor a
    ld (msx2_music_tick), a
    ld (msx2_music_step), a
    ld a, 7
    ld e, #38
    call psg_write_direct
    ld a, 8
    ld e, 11
    call psg_write_direct
    ld a, 9
    ld e, 9
    call psg_write_direct
    ld a, 10
    ld e, 7
    call psg_write_direct
    jp msx2_snake_music_apply_step

update_msx2_snake_music:
    ; Tick is called from the main loop; reload at a coarse rate to avoid
    ; overwhelming the PSG and to keep the loop musical under C-BIOS/OpenMSX.
    ld a, (msx2_music_tick)
    inc a
    ld (msx2_music_tick), a
    cp 10
    ret c
    xor a
    ld (msx2_music_tick), a
    ld a, (msx2_music_step)
    inc a
    and #0F
    ld (msx2_music_step), a
    jp msx2_snake_music_apply_step

msx2_snake_music_apply_step:
    ; Clobbers AF/BC/DE/HL. Writes tone A/B/C and stable volumes.
    ld a, (msx2_music_step)
    ld c, a
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_a_lo
    add hl, de
    ld e, (hl)
    ld a, 0
    call psg_write_direct
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_a_hi
    add hl, de
    ld e, (hl)
    ld a, 1
    call psg_write_direct
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_b_lo
    add hl, de
    ld e, (hl)
    ld a, 2
    call psg_write_direct
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_b_hi
    add hl, de
    ld e, (hl)
    ld a, 3
    call psg_write_direct
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_c_lo
    add hl, de
    ld e, (hl)
    ld a, 4
    call psg_write_direct
    ld e, c
    ld d, 0
    ld hl, msx2_music_ch_c_hi
    add hl, de
    ld e, (hl)
    ld a, 5
    call psg_write_direct
    ret

