msx2_snake_draw_cell_16:
    ; B=tile X (0..15), C=tile Y (0..11), msx2_snake_draw_char=char code. Clobbers AF/BC/DE/HL.
    ld hl, SCREEN4_NAME_VRAM
    ld a, c
    or a
    jp z, .snake_row_done
    ld de, 64
.snake_row_loop:
    add hl, de
    dec a
    jp nz, .snake_row_loop
.snake_row_done:
    ld a, b
    add a, a
    ld e, a
    ld d, 0
    add hl, de
    ld a, (msx2_snake_draw_char)
    call WRTVRM
    inc hl
    ld a, (msx2_snake_draw_char)
    inc a
    call WRTVRM
    ld de, 31
    add hl, de
    ld a, (msx2_snake_draw_char)
    add a, 2
    call WRTVRM
    inc hl
    ld a, (msx2_snake_draw_char)
    add a, 3
    call WRTVRM
    ret

