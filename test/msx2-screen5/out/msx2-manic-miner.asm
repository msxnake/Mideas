CHGMOD  EQU #005F
DISSCR  EQU #0041
ENASCR  EQU #0044
FILVRM  EQU #0056
WRTVDP  EQU #0047
LDIRVM  EQU #005C
CHGCLR  EQU #0062
CHGET   EQU #009F
HKEY    EQU #F3DB
CLIKSW  EQU #F3DC
BAKCLR  EQU #F3E9
BDRCLR  EQU #F3EA

VDP_PALETTE_PORT EQU #9A
VDP_DATA_PORT EQU #98
VDP_CTRL_PORT EQU #99
SCREEN5_BITMAP_VRAM EQU #0000
SCREEN5_BITMAP_SIZE EQU 27136

    org #4000

    db "AB"
    dw init_rom
    dw 0
    dw 0
    dw 0
    dw 0
    dw 0
    dw 0

init_rom:
    di
    im 1
    ld sp, #F380

    ld a, #C9
    ld (HKEY), a
    xor a
    ld (CLIKSW), a
    ld (BAKCLR), a
    ld (BDRCLR), a
    call CHGCLR

    call DISSCR
    ld a, 5
    call CHGMOD

    ; Enable 212-line display on V9938/V9958.
    ld bc, #8009
    call WRTVDP

    call load_screen5_palette
    call load_MSX2_MANIC_MINER_SCREEN_bitmap
    call init_hardware_sprites

    call ENASCR
    ei

    ; MSX2 minimal GameFlow: Start/Text(background)/Transition(cls)/End.
    call load_MSX2_MANIC_MINER_SCREEN_bitmap
    call wait_key
    jp .main_loop

.main_loop:
    halt
    jr .main_loop

wait_key:
    call CHGET
    ret

clear_screen5_bitmap:
    xor a
    ld hl, SCREEN5_BITMAP_VRAM
    ld bc, SCREEN5_BITMAP_SIZE
    call FILVRM
    ret

init_hardware_sprites:
    ; SCREEN 5 hardware sprite MVP. Clobbers AF/BC/DE/HL.
    ; R#1 = #E2 selects 16x16 sprites and keeps display/IRQ bits compatible with BIOS use.
    ld bc, #E201
    call WRTVDP
    ld a, #E2
    ld (#F3E0), a

    ; Sprite attribute/color/pattern tables live above the SCREEN 5 bitmap.
    ; R#5 selects SAT #7600. R#11 remains 0 because the table is below 64KB.
    ld bc, #EC05
    call WRTVDP
    ld bc, #000B
    call WRTVDP
    ld bc, #0F06
    call WRTVDP

    ld hl, msx2_hw_sprite_pattern_0
    ld de, #7800
    ld bc, 32
    call copy_to_vram_ext

    ld hl, msx2_hw_sprite_colors_0
    ld de, #7400
    ld bc, 16
    call copy_to_vram_ext

    ld hl, msx2_hw_sprite_attrs
    ld de, #7600
    ld bc, 128
    call copy_to_vram_ext

    xor a
    ld bc, #000E
    call WRTVDP
    ret

copy_to_vram_ext:
    ; HL=RAM/ROM source, DE=absolute VRAM destination, BC=length. Clobbers AF/BC/DE/HL.
    ld a, d
    and #C0
    rlca
    rlca
    out (VDP_CTRL_PORT), a
    ld a, #8E
    out (VDP_CTRL_PORT), a
    ld a, e
    out (VDP_CTRL_PORT), a
    ld a, d
    and #3F
    or #40
    out (VDP_CTRL_PORT), a
.copy_loop:
    ld a, (hl)
    out (VDP_DATA_PORT), a
    inc hl
    dec bc
    ld a, b
    or c
    jr nz, .copy_loop
    ret


load_screen5_palette:
    ; R#16 selects the first palette register; port #9A receives 2 bytes per slot.
    ld bc, #0010
    call WRTVDP
    ld hl, screen5_palette_data
    ld b, 32
.palette_loop:
    ld a, (hl)
    out (VDP_PALETTE_PORT), a
    inc hl
    djnz .palette_loop
    ret

load_MSX2_MANIC_MINER_SCREEN_bitmap:
    ld hl, MSX2_MANIC_MINER_SCREEN_BITMAP
    ld de, SCREEN5_BITMAP_VRAM
    ld bc, SCREEN5_BITMAP_SIZE
    call LDIRVM
    ret


