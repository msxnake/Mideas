init_rom:
    di
    ld sp, #F380
    call map_page2_to_cart_primary
    ; Konami SCC resident bank init (same as generator)
    xor a
    ld (#5000), a
    ld a, 1
    ld (#7000), a
    ld a, 2
    ld (#9000), a
    ld a, 3
    ld (#B000), a
    ; Read the [bank, 255-bank] signature of each test bank through P2
    ld hl, test_bank_list
    ld de, #C000
.bank_loop:
    ld a, (hl)
    cp #FF
    jp z, .scc_test
    ld (#9000), a
    push hl
    ld hl, (#8000)
    ld a, l
    ld (de), a
    inc de
    ld a, h
    ld (de), a
    inc de
    pop hl
    inc hl
    jp .bank_loop
.scc_test:
    ; Bank #3F in P2 exposes the SCC: waveform RAM #9800 must read back
    ld a, #3F
    ld (#9000), a
    ld a, #AA
    ld (#9800), a
    ld a, (#9800)
    ld (de), a
    inc de
    ld a, #55
    ld (#9800), a
    ld a, (#9800)
    ld (de), a
    ; Done marker
    ld a, #77
    ld (#C0FF), a
.halt_loop:
    jp .halt_loop

map_page2_to_cart_primary:
    call RSLREG
    rrca
    rrca
    call get_cart_slot_value
    ld h, #80
    jp ENASLT

get_cart_slot_value:
    and #03
    ld c, a
    ld b, 0
    ld hl, #FCC1
    add hl, bc
    ld a, (hl)
    and #80
    jp z, .slot_ready
    or c
    ld c, a
    inc hl
    inc hl
    inc hl
    inc hl
    ld a, (hl)
    and #0C
.slot_ready:
    or c
    ret

