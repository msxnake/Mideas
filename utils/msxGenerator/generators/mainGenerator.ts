/**
 * @fileoverview Main Generator - Main assembly file with includes
 * Generates main.asm with ordered includes and main program entry point
 */

import { ProjectAnalysis } from '../../asmTemplateGenerator';

/**
 * Generate main.asm with ordered imports
 *
 * @param projectName - Name of the project
 * @param analysis - Project analysis with assets and GameFlow
 * @returns ASM code string with main program structure
 */
export function generateMainFile(projectName: string, analysis: ProjectAnalysis): string {
    return `; ==================================================================
; ${projectName.toUpperCase()} - MAIN ASSEMBLY FILE
; File: main.asm
; Description: Main file with ordered imports for MSX cartridge
; Generated by Mideas MSX Generator
; ==================================================================

; ==================================================================
; ORDERED INCLUDES - RIGOROUS ORDER MATTERS!
; ==================================================================

; 1. BIOS Functions (must be first)
include "bios.asm"

; 2. Constants (depends on BIOS)
include "constants.asm"

; 3. Variables (depends on constants)
include "variables.asm"

; 4. ROM Header (depends on variables)
include "header.asm"

${analysis.tiles && analysis.tiles.length > 0 ? `; 5. Pattern Data (if tiles exist)
include "patterns.asm"

; 6. Color Data (if tiles exist)
include "colors.asm"
` : ''}

${analysis.sprites && analysis.sprites.length > 0 ? `; 7. Sprite Data (if sprites exist)
include "sprites.asm"
` : ''}

; 8. Components (game logic)
include "components.asm"

; 9. Entities (game objects)
include "entities.asm"

${analysis.worldmaps && (analysis.worldmaps as any[]).length > 0 ? `; 10. Worlds (world maps)
include "worlds.asm"
` : ''}

${analysis.screenMaps && analysis.screenMaps.length > 0 ? `; 11. Screen Maps (if screens exist)
include "screens.asm"
` : ''}

; 12. Font Data (custom font for Screen 2 text)
include "font.asm"

; 13. HUD System (heads-up display)
include "hud.asm"

; 14. Menus (user interface)
include "menus.asm"

${analysis.stateMachines && analysis.stateMachines.length > 0 ? `; 15. State Machines (entity AI)
include "statemachine.asm"
` : ''}

; 16. GameFlow (game flow state machine)
include "gameflow.asm"

; ==================================================================
; MAIN PROGRAM ENTRY POINT
; ==================================================================
main_program:
    ; Initialize game systems
    call init_game_systems

    ; Initialize font system for Screen 2 text
    call init_font_system

    ; Initialize Game Flow system
    xor a
    ld (current_flow_state), a
    ld (prev_flow_state), a

    ; Load initial screen based on GameFlow (Critical for Paridad)
    call load_game_screen

    ; Main game loop
main_loop:
    halt                 ; Wait for V-Blank

    ; Update current game state
    call update_current_state

    ; Render current frame
    call render_frame

    ; Loop forever
    jp main_loop

; ==================================================================
; GAME SYSTEM FUNCTIONS (implemented in components.asm)
; ==================================================================
init_game_systems:
    ; Initialize all game systems
    call init_components
    call init_entities       ; Initialize entities (positions, screens, etc.) and sprites
    ret

update_current_state:
    ; Update game logic based on current state
    call update_input_component
    call update_behavior_component  ; AI/Logic
    call update_statemachine_component  ; State Machine updates
    call update_movement_component
    call update_position_component
    call update_collision_component
    call update_health_component    ; Health/Death checks
    call update_animation_component ; Sprite animations
    call update_sprite_component    ; Render sprites
    ret

render_frame:
    ; Render current frame
    ; This function is implemented in the unified assembly
    ; Game rendering is handled by component systems
    ret

; ==================================================================
; END OF MAIN PROGRAM
; ==================================================================
    end                 ; End of assembly
`;
}

