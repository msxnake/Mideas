; music_trigger_channel_attack
; Hook kept for compatibility. The preview-style hardware envelope is
; emulated in software per channel, so new-note state is already reset
; by music_apply_channel_cell before this helper is called.
; Input:  C = channel index (0=A, 1=B, 2=C)
; Output: None
; Destroys: None
; ------------------------------------------------------------------
music_trigger_channel_attack:
    ret

; ------------------------------------------------------------------
; music_resolve_channel_volume
; Resolve per-frame channel volume.
; Current Phase 1 behavior:
; - emulates AY hardware envelope shapes in software when ayEnvelopeShape is set
; - falls back to music_ch_volume_base when no envelope data exists
; - applies a simple software volumeEnvelope when present
; Input:  C = channel index (0=A, 1=B, 2=C)
; Output: B = PSG volume 0-15
; Destroys: AF, DE, HL
; ------------------------------------------------------------------
music_resolve_channel_volume:
    push af
    push de
    push hl
    ld hl, music_ch_instrument_base
    call music_load_channel_byte
    or a
    jp z, .fallback_base
    call music_get_instrument_ptr
    ld a, h
    or l
    jp z, .fallback_base
    ld a, (hl)
    and #04
    jp nz, .hardware_env
.check_software_env:
    push hl
    ld de, 8
    add hl, de
    ld b, (hl)
    pop hl
    ld a, b
    or a
    jp z, .fallback_base
    push hl
    ld de, 6
    add hl, de
    ld e, (hl)
    inc hl
    ld d, (hl)
    pop hl
    push hl
    ld hl, music_ch_vol_step_base
    call music_load_channel_byte
    cp b
    jr c, .step_ok_restore
    pop hl
    push de
    push hl
    ld de, 9
    add hl, de
    ld a, (hl)
    pop hl
    pop de
    cp b
    jr c, .step_ok
    ld a, b
    push af
    ld hl, music_ch_vol_step_base
    call music_store_channel_byte
    pop af
    ld hl, music_ch_note_base
    ld a, #FF
    call music_store_channel_byte
    xor a
    ld b, a
    jp .mrcv_done
.step_ok_restore:
    pop hl
.step_ok:
    push af
    inc a
    cp b
    jr c, .next_step_ok
    push de
    push hl
    ld de, 9
    add hl, de
    ld a, (hl)
    pop hl
    pop de
    cp b
    jr c, .next_step_ok
    ld a, b
.next_step_ok:
    push de
    ld hl, music_ch_vol_step_base
    call music_store_channel_byte
    pop de
    pop af
    ld l, a
    ld h, 0
    add hl, de
    ld a, (hl)
    cp 16
    jr c, .env_volume_ok
    ld a, 15
.env_volume_ok:
    ld b, a
    jp .mrcv_done
.hardware_env:
    ld hl, music_ch_tone_step_base
    call music_load_channel_byte
    inc a
    cp 2
    jr c, .hw_store_counter
    xor a
    push af
    ld hl, music_ch_tone_step_base
    call music_store_channel_byte
    pop af
    ld hl, music_ch_vol_step_base
    call music_load_channel_byte
    cp 15
    jr nc, .hw_phase_ready
    inc a
    push af
    ld hl, music_ch_vol_step_base
    call music_store_channel_byte
    pop af
    jr .hw_phase_ready
.hw_store_counter:
    push af
    ld hl, music_ch_tone_step_base
    call music_store_channel_byte
    pop af
    ld hl, music_ch_vol_step_base
    call music_load_channel_byte
.hw_phase_ready:
    push af
    call music_get_channel_instrument_ptr
    ld a, h
    or l
    pop af
    jr z, .hw_decay
    push af
    inc hl
    inc hl
    ld a, (hl)
    and #04
    pop af
    jr z, .hw_decay
    ld b, a
    jp .mrcv_done
.hw_decay:
    ld e, a
    ld a, 15
    sub e
    ld b, a
    jp .mrcv_done
.fallback_base:
    ld hl, music_ch_volume_base
    call music_load_channel_byte
    ld b, a
.mrcv_done:
    pop hl
    pop de
    pop af
    ret

; ------------------------------------------------------------------
; music_resolve_channel_noise
; Resolve per-frame channel noise period, including the PT3-inspired
; software noise macro appended to the instrument descriptor.
; Input:  C = channel index (0=A, 1=B, 2=C)
; Output: A = PSG noise period 0-31
; Destroys: AF, DE, HL
; Preserves: Stack balance restored before return
; ------------------------------------------------------------------
music_resolve_channel_noise:
    push de
    push hl
    ld hl, music_ch_instrument_base
    call music_load_channel_byte
    or a
    jp z, .mrcn_track_default
    call music_get_instrument_ptr
    ld a, h
    or l
    jp z, .mrcn_track_default
    push hl
    ld de, 16
    add hl, de
    ld b, (hl)
    pop hl
    ld a, b
    or a
    jp z, .mrcn_static_noise
    push hl
    ld hl, music_ch_noise_step_base
    call music_load_channel_byte
    cp b
    jr c, .mrcn_step_ok
    ld a, b
    dec a
.mrcn_step_ok:
    push af
    pop af
    pop hl
    push af
    inc a
    cp b
    jr c, .mrcn_store_next
    push de
    ld de, 17
    add hl, de
    ld a, (hl)
    pop de
    cp b
    jr c, .mrcn_store_next
    ld a, b
    dec a
.mrcn_store_next:
    push hl
    push af
    ld hl, music_ch_noise_step_base
    call music_store_channel_byte
    pop af
    pop hl
    ld de, 14
    add hl, de
    ld e, (hl)
    inc hl
    ld d, (hl)
    pop af
    ld l, a
    ld h, 0
    add hl, de
    ld a, (hl)
    and #1F
    jp .mrcn_done
.mrcn_static_noise:
    push de
    ld de, 3
    add hl, de
    ld a, (hl)
    pop de
    and #1F
    jp .mrcn_done
.mrcn_track_default:
    ld a, MUSIC_TRACK_NOISE_DEFAULT
    call music_read_track_byte
    and #1F
.mrcn_done:
    pop hl
    pop de
    ret

; ------------------------------------------------------------------
; music_play_track
; Start a serialized PSG tracker song from ROM.
; Input:  A = track index in music_track_ptr_table
;         B bit 0 = loop enabled flag
; Output: music_active=1 and first row applied immediately
; Destroys: AF, BC, DE, HL
; Preserves: Stack balance restored on all exits
; ------------------------------------------------------------------
music_play_track:
    push bc
    push de
    push hl
    ld hl, music_track_count
    cp (hl)
    jp nc, .mpt_done
    ld (music_track_index), a
    call music_load_track_pointer_from_index
    jp c, .mpt_done
    ld a, b
    and 1
    ld (music_loop), a
    xor a
    ld (music_muted), a
    ld (music_order_pos), a
    ld (music_pattern_index), a
    ld (music_pattern_row), a
    ld a, 1
    ld (music_active), a
    call music_reset_channel_state
    call music_apply_row
.mpt_done:
    pop hl
    pop de
    pop bc
    ret

music_store_channel_byte:
    push de
    ld e, c
    ld d, 0
    add hl, de
    ld (hl), a
    pop de
    ret

music_load_channel_byte:
    push de
    ld e, c
    ld d, 0
    add hl, de
    ld a, (hl)
    pop de
    ret

music_apply_channel_cell:
    ld c, a
    ld d, 0
    ld a, (hl)
    inc hl
    cp #FF
    jp z, .note_done
    cp #FE
    jp nz, .store_note
    ld a, #FF
    jr .store_note
.store_note:
    cp #FF
    jr z, .store_note_value
    ld d, 1
.store_note_value:
    push hl
    ld hl, music_ch_note_base
    call music_store_channel_byte
    xor a
    ld hl, music_ch_vol_step_base
    call music_store_channel_byte
    ld hl, music_ch_tone_step_base
    call music_store_channel_byte
    ld hl, music_ch_noise_step_base
    call music_store_channel_byte
    ld hl, music_ch_orn_step_base
    call music_store_channel_byte
    pop hl
.note_done:
    ld a, (hl)
    inc hl
    cp #FF
    jp z, .instrument_done
    push hl
    ld hl, music_ch_instrument_base
    call music_store_channel_byte
    pop hl
.instrument_done:
    ld a, (hl)
    inc hl
    cp #FF
    jp z, .ornament_done
    push hl
    ld hl, music_ch_ornament_base
    call music_store_channel_byte
    pop hl
.ornament_done:
    ld a, (hl)
    inc hl
    cp #FF
    jr z, .maybe_trigger_attack
    push hl
    ld hl, music_ch_volume_base
    call music_store_channel_byte
    pop hl
.maybe_trigger_attack:
    ld a, d
    or a
    ret z
    push hl
    call music_trigger_channel_attack
    pop hl
    ret

; ------------------------------------------------------------------
; music_apply_row
; Decode current order/pattern row and cache channel state for A/B/C.
; Input:  Runtime variables select track/order/pattern position
; Output: Channel note/instrument/volume caches updated
;         Row countdown reloaded and PSG refreshed once
; Destroys: AF, BC, DE, HL
; ------------------------------------------------------------------
music_apply_row:
    ld a, MUSIC_TRACK_ORDER_TABLE
    call music_read_track_word
    ld a, (music_order_pos)
    ld e, a
    ld d, 0
    add hl, de
    ld a, (hl)
    ld (music_pattern_index), a
    ld a, MUSIC_TRACK_PATTERN_TABLE
    call music_read_track_word
    ld a, (music_pattern_index)
    ld e, a
    ld d, 0
    add hl, de
    add hl, de
    add hl, de
    ld e, (hl)
    inc hl
    ld d, (hl)
    inc hl
    ld a, (hl)
    ld (music_pattern_rows), a
    ld a, e
    ld (music_pattern_ptr_l), a
    ld a, d
    ld (music_pattern_ptr_h), a
    ld h, d
    ld l, e
    ld a, (music_pattern_row)
    or a
    jp z, .row_ptr_ready
    ld b, a
.row_offset_loop:
    ld de, 12
    add hl, de
    djnz .row_offset_loop
.row_ptr_ready:
    xor a
    call music_apply_channel_cell
    ld a, 1
    call music_apply_channel_cell
    ld a, 2
    call music_apply_channel_cell
    ld a, (music_pattern_row)
    inc a
    ld d, a
    ld a, (music_pattern_rows)
    cp d
    jp z, .advance_order
    jp c, .advance_order
    ld a, d
    ld (music_pattern_row), a
    jp .row_done
.advance_order:
    xor a
    ld (music_pattern_row), a
    ld a, (music_order_pos)
    inc a
    ld d, a
    ld a, 1
    call music_read_track_byte
    cp d
    jp z, .end_of_order
    jp c, .end_of_order
    ld a, d
    ld (music_order_pos), a
    jp .row_done
.end_of_order:
    ld a, (music_loop)
    or a
    jp z, music_stop
    ld a, 2
    call music_read_track_byte
    ld (music_order_pos), a
.row_done:
    xor a
    call music_read_track_byte
    ld (music_row_frames), a
    ld (music_row_countdown), a
    call music_update_channel_effects
    ret

; ------------------------------------------------------------------
; music_update
; Advance the tracker once per game frame.
; Input:  None
; Output: Current channel PSG state refreshed; next row applied when due
; Destroys: AF, BC, DE, HL
; ------------------------------------------------------------------
music_update:
    ld a, (music_active)
    or a
    ret z
    ld a, (music_muted)
    or a
    ret nz
    call music_update_channel_effects
    ld a, (music_row_countdown)
    or a
    jp z, music_apply_row
    dec a
    ld (music_row_countdown), a
    ret nz
    call music_apply_row
    ret

; ------------------------------------------------------------------
; music_update_channel_effects
; Rebuild mixer bits and push current cached channel state to PSG.
; Input:  music_ch_* caches already populated
; Output: PSG tone/volume registers updated for channels A/B/C
;         music_mixer_shadow rewritten with current enable bits
; Destroys: AF, BC, DE, HL
; ------------------------------------------------------------------
music_update_channel_effects:
    ld a, #3F
    ld (music_mixer_shadow), a
    ld c, 0
    call music_update_one_channel
    ld c, 1
    call music_update_one_channel
    ld c, 2
    call music_update_one_channel
    ld a, (music_mixer_shadow)
    call psg_set_mixer
    ret

; ------------------------------------------------------------------
; music_update_one_channel
; Apply one cached channel to PSG and update the mixer shadow bits.
; Input:  C = channel index (0=A, 1=B, 2=C)
; Output: Channel PSG tone/volume updated or silenced
;         music_mixer_shadow updated for that channel
; Destroys: AF, BC, DE, HL
; Preserves: Stack balance restored before return
; ------------------------------------------------------------------
music_update_one_channel:
    push bc
    push de
    push hl
    ld hl, music_ch_note_base
    call music_load_channel_byte
    cp #FF
    jp z, .silent_channel
    add a, a
    ld e, a
    ld d, 0
    ld hl, music_note_period_table
    add hl, de
    ld e, (hl)
    inc hl
    ld d, (hl)
    ld h, d
    ld l, e
    ld a, c
    push bc
    call psg_set_tone
    pop bc
    call music_resolve_channel_volume
    ld a, c
    push bc
    call psg_set_volume
    pop bc
    ld d, 1
    ld e, 0
    call music_get_channel_instrument_ptr
    ld a, h
    or l
    jr z, .apply_mixer_bits
    ld a, (hl)
    and #01
    ld d, a
    ld a, (hl)
    and #02
    srl a
    ld e, a
    ld a, e
    or a
    jr z, .apply_mixer_bits
    push de
    call music_resolve_channel_noise
    call psg_set_noise
    pop de
.apply_mixer_bits:
    ld a, (music_mixer_shadow)
    ld b, a
    ld a, c
    cp 1
    jp z, .enable_b
    cp 2
    jp z, .enable_c
    ld a, b
    bit 0, d
    jr z, .a_tone_off
    and #3E
    jr .a_noise_gate
.a_tone_off:
    or #01
.a_noise_gate:
    bit 0, e
    jr z, .a_noise_off
    and #37
    jp .store_mixer
.a_noise_off:
    or #08
    jp .store_mixer
.enable_b:
    ld a, b
    bit 0, d
    jr z, .b_tone_off
    and #3D
    jr .b_noise_gate
.b_tone_off:
    or #02
.b_noise_gate:
    bit 0, e
    jr z, .b_noise_off
    and #2F
    jp .store_mixer
.b_noise_off:
    or #10
    jp .store_mixer
.enable_c:
    ld a, b
    bit 0, d
    jr z, .c_tone_off
    and #3B
    jr .c_noise_gate
.c_tone_off:
    or #04
.c_noise_gate:
    bit 0, e
    jr z, .c_noise_off
    and #1F
    jp .store_mixer
.c_noise_off:
    or #20
    jp .store_mixer
.silent_channel:
    ld b, 0
    ld a, c
    push bc
    call psg_set_volume
    pop bc
    ld a, (music_mixer_shadow)
    ld b, a
    ld a, c
    cp 1
    jp z, .disable_b
    cp 2
    jp z, .disable_c
    ld a, b
    or #09
    jp .store_mixer
.disable_b:
    ld a, b
    or #12
    jp .store_mixer
.disable_c:
    ld a, b
    or #24
.store_mixer:
    ld (music_mixer_shadow), a
    pop hl
    pop de
    pop bc
    ret

