function getDynamicFarEntryPoints(moduleKey, content) {
    const labels = new Set();
    const patterns = [];
    if (moduleKey === 'patterns_code') {
        patterns.push(/^((?:load_tilebank_[A-Za-z0-9_]+_patterns_to_vram)):/gm);
    }
    else if (moduleKey === 'colors_code') {
        patterns.push(/^((?:load_tilebank_[A-Za-z0-9_]+_colors_to_vram)):/gm);
    }
    for (const pattern of patterns) {
        for (const match of content.matchAll(pattern)) {
            labels.add(match[1]);
        }
    }
    return [...labels];
}
function collectDefinedLabels(files) {
    const labels = new Set();
    const labelPattern = /^\s*([A-Za-z_][A-Za-z0-9_]*):/gm;
    Object.values(files).forEach((asm = '') => {
        for (const match of asm.matchAll(labelPattern)) {
            labels.add(match[1]);
        }
    });
    return labels;
}
function collectCallTargets(asm) {
    const calls = [];
    const callPattern = /\b(?:call|jp)\s+([A-Za-z_][A-Za-z0-9_]*)\b/i;
    asm.split(/\r?\n/).forEach((line, index) => {
        const code = line.split(';')[0];
        const match = code.match(callPattern);
        if (match) {
            calls.push({ target: match[1], line: index + 1 });
        }
    });
    return calls;
}
function collectEstimatedLabelOffsets(asm) {
    const labels = new Map();
    let estimatedOffset = 0;
    asm.split(/\r?\n/).forEach((line, index) => {
        const code = line.split(';')[0].trim();
        const labelMatch = code.match(/^([A-Za-z_][A-Za-z0-9_]*):$/);
        if (labelMatch) {
            labels.set(labelMatch[1], { line: index + 1, estimatedOffset });
        }
        estimatedOffset += estimateAsmLineBytesLocal(line);
    });
    return labels;
}
