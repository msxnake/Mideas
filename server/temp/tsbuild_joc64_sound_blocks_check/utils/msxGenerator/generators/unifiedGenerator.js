function estimateAsmBytesLocal(asm) {
    if (!asm)
        return 0;
    let dataBytes = 0;
    const lines = asm.split(/\r?\n/);
    for (const line of lines) {
        const clean = line.split(';')[0].trim();
        if (!clean)
            continue;
        const dbMatch = clean.match(/^db\s+(.+)$/i);
        if (dbMatch) {
            dataBytes += dbMatch[1].split(',').filter(t => t.trim().length > 0).length;
            continue;
        }
        const dwMatch = clean.match(/^dw\s+(.+)$/i);
        if (dwMatch) {
            dataBytes += dwMatch[1].split(',').filter(t => t.trim().length > 0).length * 2;
            continue;
        }
        const dsMatch = clean.match(/^ds\s+([^,]+)/i);
        if (dsMatch) {
            const v = dsMatch[1].trim().toLowerCase();
            const n = /^\d+$/.test(v) ? parseInt(v, 10) : /^#([0-9a-f]+)$/.test(v) ? parseInt(v.slice(1), 16) : 0;
            if (n > 0)
                dataBytes += n;
        }
    }
    const textBytes = asm.length;
    return Math.max(dataBytes, Math.floor(textBytes * 0.28));
}
function parseAsmNumericLiteralLocal(raw) {
    const value = raw.trim().toLowerCase();
    if (/^\d+$/.test(value))
        return parseInt(value, 10);
    if (/^#([0-9a-f]+)$/.test(value))
        return parseInt(value.slice(1), 16);
    if (/^0x([0-9a-f]+)$/.test(value))
        return parseInt(value.slice(2), 16);
    if (/^([0-9a-f]+)h$/.test(value))
        return parseInt(value.slice(0, -1), 16);
    return 0;
}
// Lightweight size estimator used only for diagnostics before Glass has the
// final symbol addresses. The Python build script verifies actual bank ends
// from .sym output after assembly.
function estimateAsmLineBytesLocal(line) {
    const code = line.split(';')[0].trim();
    if (!code)
        return 0;
    if (/^[A-Za-z_][A-Za-z0-9_]*:$/.test(code))
        return 0;
    const dbMatch = code.match(/^db\s+(.+)$/i);
    if (dbMatch)
        return dbMatch[1].split(',').filter(t => t.trim().length > 0).length;
    const dwMatch = code.match(/^dw\s+(.+)$/i);
    if (dwMatch)
        return dwMatch[1].split(',').filter(t => t.trim().length > 0).length * 2;
    const dsMatch = code.match(/^ds\s+([^,]+)/i);
    if (dsMatch)
        return parseAsmNumericLiteralLocal(dsMatch[1]);
    return Math.max(1, Math.floor(code.length * 0.28));
}
