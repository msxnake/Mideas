; ------------------------------------------------------------------
; ------------------------------------------------------------------
; mapper_call_hl_fixed
; Direct call helper for Konami fixed window (#4000-#5FFF).
; Input:
;   HL = target routine address in fixed window
; Preserves: DE across mapper trampoline code
