mapper_call_hl_fixed:
    push de
    ld de, .return_fixed
    push de
    jp (hl)
.return_fixed:
    pop de
    ret

; ------------------------------------------------------------------
; mapper_call_hl_auto
; Auto-select mapper window from HL target address range:
;   4000-5FFF -> fixed
;   6000-7FFF -> p1
;   8000-9FFF -> p2
;   A000-BFFF -> p3
; Input:
;   A = target bank
;   HL = target routine address
