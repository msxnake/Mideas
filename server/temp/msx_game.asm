; ==================================================================
; TASK_UPDATE_INPUT - Joystick/Cursor polling wrapper
; ==================================================================
; Register Contract:
;   Purpose: Poll joystick + keyboard fallback and update input state buffers.
;   Inputs:
;     - Reads hardware via FAST_GTSTCK / FAST_GTTRIG / FAST_SNSMAT
;   Outputs:
;     - input_state, prev_input_state, input_btn_curr, input_btn_prev, input_fire
;   Clobbers:
;     - AF
;     - BC
;     - DE
;   Preserved:
;     - AF
;     - BC
;     - DE (by push/pop wrapper)
;     - HL
;   Register roles:
;     - A = hardware reads and final scalar writes
;     - B = direction accumulator
;     - C = logical button bitmask after control remap
;     - D = physical button bitmask and keyboard direction flags
;     - E = temporary keyboard row bits
;   Notes:
;     - Wrapper preserves caller-visible regs despite internal mutation.
task_update_input:
    push af
    push bc
    push de

    ; Save previous state
    ld a, (input_state)
    ld (prev_input_state), a
    ld a, (input_btn_curr)
    ld (input_btn_prev), a

    ; Read joystick direction first (priority source, direct hardware)
    xor a                       ; Joystick 0
    call FAST_GTSTCK            ; Direct hardware read
    ld b, a                     ; B = joystick direction
    or a
    jp nz, .dir_ready

    ; Fallback to keyboard cursor keys (row 8, direct matrix read)
    ld a, 8
    call FAST_SNSMAT            ; Active low bits
    ld e, a
    xor a
    ld d, a                     ; D = direction flags: 0=none
    bit 5, e                    ; Up
    jr nz, .kbd_no_up
    set 0, d
.kbd_no_up:
    bit 6, e                    ; Down
    jr nz, .kbd_no_down
    set 1, d
.kbd_no_down:
    bit 4, e                    ; Left
    jr nz, .kbd_no_left
    set 2, d
.kbd_no_left:
    bit 7, e                    ; Right
    jr nz, .kbd_no_right
    set 3, d
.kbd_no_right:
    ; Cancel impossible opposite cursor pairs before mapping to STICK_*
    bit 0, d                    ; Up pressed?
    jr z, .kbd_vertical_ok
    bit 1, d                    ; Down also pressed?
    jr z, .kbd_vertical_ok
    res 0, d
    res 1, d
.kbd_vertical_ok:
    bit 2, d                    ; Left pressed?
    jr z, .kbd_opposites_done
    bit 3, d                    ; Right also pressed?
    jr z, .kbd_opposites_done
    res 2, d
    res 3, d
.kbd_opposites_done:
    xor a
    bit 0, d
    jr z, .kbd_check_down
    bit 3, d
    jr nz, .kbd_upright
    bit 2, d
    jr nz, .kbd_upleft
    ld a, STICK_UP
    jr .kbd_done
.kbd_upright:
    ld a, STICK_UPRIGHT
    jr .kbd_done
.kbd_upleft:
    ld a, STICK_UPLEFT
    jr .kbd_done
.kbd_check_down:
    bit 1, d
    jr z, .kbd_check_lr
    bit 3, d
    jr nz, .kbd_downright
    bit 2, d
    jr nz, .kbd_downleft
    ld a, STICK_DOWN
    jr .kbd_done
.kbd_downright:
    ld a, STICK_DOWNRIGHT
    jr .kbd_done
.kbd_downleft:
    ld a, STICK_DOWNLEFT
    jr .kbd_done
.kbd_check_lr:
    bit 2, d
    jr z, .kbd_check_right
    ld a, STICK_LEFT
    jr .kbd_done
.kbd_check_right:
    bit 3, d
    jr z, .kbd_done
    ld a, STICK_RIGHT
.kbd_done:
    ld b, a
.dir_ready:
    ; Normalize diagonals to cardinal directions for runtime stability
    ; UP+RIGHT/DOWN+RIGHT -> RIGHT, UP+LEFT/DOWN+LEFT -> LEFT
    ld a, b
    cp STICK_UPRIGHT
    jr z, .dir_norm_right
    cp STICK_DOWNRIGHT
    jr z, .dir_norm_right
    cp STICK_UPLEFT
    jr z, .dir_norm_left
    cp STICK_DOWNLEFT
    jr z, .dir_norm_left
    jr .dir_norm_done
.dir_norm_right:
    ld a, STICK_RIGHT
    jr .dir_norm_store
.dir_norm_left:
    ld a, STICK_LEFT
.dir_norm_store:
    ld b, a
.dir_norm_done:
    ld d, 0                     ; D = physical button bitmask (bit0=button1, bit1=button2)
    xor a                       ; Joystick 0 button A -> physical button 1
    call FAST_GTTRIG            ; A = #FF if pressed, 0 if not
    or a
    jr z, .phys_btn1_keyboard
    set 0, d
.phys_btn1_keyboard:
    ld a, (input_key_button1_mode)
    or a
    jr nz, .phys_btn1_ctrl
    ld a, 8                    ; SPACE row
    call FAST_SNSMAT
    bit 0, a                   ; SPC (active low)
    jr nz, .phys_btn1_done
    set 0, d
    jr .phys_btn1_done
.phys_btn1_ctrl:
    ld a, 6                    ; CTRL row
    call FAST_SNSMAT
    bit 2, a                   ; CTRL (active low)
    jr nz, .phys_btn1_done
    set 0, d
.phys_btn1_done:
    ; Joystick button B or configured keyboard key -> physical button 2
    push bc
    push hl
    ld a, 3                    ; GTTRIG(3) = joystick 1 button B
    call GTTRIG
    ld e, a
    pop hl
    pop bc
    ld a, e
    or a
    jr z, .phys_btn2_keyboard
    set 1, d
.phys_btn2_keyboard:
    ld a, (input_key_button2_mode)
    or a
    jr nz, .phys_btn2_ctrl
    ld a, 4                    ; Keyboard row containing N
    call FAST_SNSMAT
    bit 3, a                   ; N key (active low)
    jr nz, .phys_btn2_done
    set 1, d
    jr .phys_btn2_done
.phys_btn2_ctrl:
    ld a, 6                    ; CTRL row
    call FAST_SNSMAT
    bit 2, a                   ; CTRL (active low)
    jr nz, .phys_btn2_done
    set 1, d
.phys_btn2_done:
    ld c, 0                    ; C = logical buttons after action remap
    ld a, (control_jump_button)
    or a
    jr nz, .jump_uses_btn2
    bit 0, d
    jr z, .jump_done
    set 0, c                   ; logical fire/jump
    jr .jump_done
.jump_uses_btn2:
    bit 1, d
    jr z, .jump_done
    set 0, c
.jump_done:
    ld a, (control_action_button)
    or a
    jr nz, .action_uses_btn2
    bit 0, d
    jr z, .action_done
    set 1, c                   ; logical action/grab
    jr .action_done
.action_uses_btn2:
    bit 1, d
    jr z, .action_done
    set 1, c
.action_done:
    ld a, c
    and INPUT_BTN_FIRE
    jr z, .fire_state_released
    ld a, 1
    jr .store_fire_state
.fire_state_released:
